/* Generates app/hover.css from lib/hoverStyles.ts.
 *
 * Mirrors what support.js did at runtime: one class per hover style, with
 * !important appended to every declaration so the rule beats the inline
 * base styles carried over from v2-maven.
 *
 *   node scripts/gen-hover-css.mjs           write app/hover.css
 *   node scripts/gen-hover-css.mjs --check   fail if out of date (CI)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const app = path.dirname(here);
const src = path.join(app, "lib", "hoverStyles.ts");
const out = path.join(app, "app", "hover.css");

/* Parse the object literal rather than importing it, so this script needs no
 * TypeScript toolchain and cannot drag app code into the build. */
const ts = fs.readFileSync(src, "utf8");
function parseMap(name) {
  const re = new RegExp(
    `export const ${name} = \\{([\\s\\S]*?)\\n\\} as const;`,
  );
  const body = ts.match(re);
  if (!body) {
    console.error(`could not locate ${name} in lib/hoverStyles.ts`);
    process.exit(2);
  }
  return [...body[1].matchAll(/^\s*([A-Za-z0-9_]+):\s*"([^"]*)"/gm)].map(
    (m) => [m[1], m[2]],
  );
}

const entries = parseMap("HOVER_STYLES");
const focusEntries = parseMap("FOCUS_STYLES");
if (!entries.length) {
  console.error("HOVER_STYLES parsed but empty");
  process.exit(2);
}

/** Append !important to each declaration, as importantify() did. */
function importantify(css) {
  return css
    .split(";")
    .map((d) => d.trim())
    .filter(Boolean)
    .map((d) => (/!\s*important$/i.test(d) ? d : `${d} !important`))
    .join("; ");
}

const lines = [
  "/* GENERATED by scripts/gen-hover-css.mjs from lib/hoverStyles.ts.",
  " * Do not edit by hand - run `npm run gen:hover`.",
  " *",
  " * Replaces v2-maven's style-hover attribute. !important is required:",
  " * base styles are inline and would otherwise beat these rules.",
  " */",
  "",
];
for (const [name, css] of entries) {
  lines.push(`.hv-${name}:hover { ${importantify(css)}; }`);
}
for (const [name, css] of focusEntries) {
  lines.push(`.fv-${name}:focus-visible { ${importantify(css)}; }`);
}
const text = lines.join("\n") + "\n";

if (process.argv.includes("--check")) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (current !== text) {
    console.error("app/hover.css is out of date - run `npm run gen:hover`");
    process.exit(1);
  }
  console.log(
    `hover.css up to date (${entries.length + focusEntries.length} rules)`,
  );
} else {
  fs.writeFileSync(out, text);
  console.log(
    `wrote app/hover.css (${entries.length + focusEntries.length} rules)`,
  );
}
